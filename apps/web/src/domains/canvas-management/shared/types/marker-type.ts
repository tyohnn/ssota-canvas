/**
 * Marker type for edge arrow display.
 * - none: no marker
 * - arrow: closed arrow (filled triangle)
 * - arrow-open: open arrow (outline only)
 * - circle: filled circle
 * - circle-open: open circle (outline only)
 * - diamond: filled diamond
 * - diamond-open: open diamond (outline only)
 */
export type MarkerType =
  | 'none'
  | 'arrow'
  | 'arrow-open'
  | 'circle'
  | 'circle-open'
  | 'diamond'
  | 'diamond-open';
